// Writes src/suffixes.ts from the Public Suffix List's ICANN section (https://publicsuffix.org,
// MPL 2.0): `pnpm suffixes`, then commit the module. Only ICANN's suffixes: the private section
// (github.io, workers.dev…) would make names anyone can get under a service count as domains of
// their own, the subdomains that per-domain limits must keep together (src/app.ts, PER_DOMAIN).
// Rules are kept in ASCII (IDNs as punycode), as the Worker compares them.

import { writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const response = await fetch("https://publicsuffix.org/list/public_suffix_list.dat");
if (!response.ok) throw new Error(`The Public Suffix List couldn't be read: HTTP ${response.status}`);
const text = await response.text();
const icann = text.slice(text.indexOf("// ===BEGIN ICANN DOMAINS==="), text.indexOf("// ===END ICANN DOMAINS==="));
const version = /\/\/ VERSION: (\S+)/.exec(text)?.[1] ?? "unknown";
const rules = new Set();
for (const line of icann.split("\n")) {
  const rule = line.trim().split(/\s/)[0];
  if (!rule || rule.startsWith("//")) continue;
  const prefix = rule.startsWith("!") ? "!" : rule.startsWith("*.") ? "*." : "";
  const name = domainToASCII(rule.slice(prefix.length));
  if (!name) throw new Error(`A rule that isn't a domain: ${rule}`);
  rules.add(prefix + name);
}
if (rules.size < 5000 || !rules.has("ac.in") || !rules.has("co.uk") || !rules.has("com")) throw new Error(`The list looks wrong: ${rules.size} rules`);
writeFileSync(
  new URL("../src/suffixes.ts", import.meta.url),
  `// Generated by scripts/suffixes.mjs from the Public Suffix List's ICANN section (${version}),
// https://publicsuffix.org, under the Mozilla Public License 2.0. Don't edit: run \`pnpm suffixes\`.
// One rule a line: a suffix, \`*.\` a wildcard, \`!\` an exception.

export const PUBLIC_SUFFIXES = new Set(${JSON.stringify([...rules].sort().join("\n"))}.split("\\n"));
`,
);
console.log(`${rules.size} rules, ${version}`);
